CREATE OR REPLACE FUNCTION public.search_available_rooms(
  p_check_in_date date,
  p_check_out_date date,
  p_guests integer,
  p_branch_id bigint DEFAULT NULL,
  p_room_type_id bigint DEFAULT NULL,
  p_min_price bigint DEFAULT NULL,
  p_max_price bigint DEFAULT NULL
)
RETURNS TABLE (
  room_id bigint, branch_id bigint, branch_name character varying,
  branch_city character varying, room_type_id bigint,
  room_type_name character varying, room_type_capacity integer,
  room_type_bed_type character varying, room_type_area_m2 numeric,
  room_number character varying, room_name character varying,
  room_description text, price_per_night bigint, image_url text,
  image_alt_text character varying
)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $function$
BEGIN
  IF p_check_in_date IS NULL OR p_check_out_date IS NULL
     OR p_check_out_date <= p_check_in_date OR p_check_in_date < CURRENT_DATE THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'The availability date range is invalid.';
  END IF;
  IF p_guests IS NULL OR p_guests < 1 THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'The guest count is invalid.';
  END IF;

  RETURN QUERY
  SELECT r.id, b.id, b.name, b.city, rt.id,
    (rt.name || ' - ' || rc.name)::character varying, rt.capacity,
    rt.bed_type, rt.area_m2, NULL::character varying, r.name, r.description,
    r.price_per_night, img.image_url, img.alt_text
  FROM public.rooms r
  JOIN public.branches b ON b.id = r.branch_id
  JOIN public.room_types rt ON rt.id = r.room_type_id
  JOIN public.room_classes rc ON rc.id = r.room_class_id
  LEFT JOIN LATERAL (
    SELECT ri.image_url, ri.alt_text FROM public.room_images ri
    WHERE ri.room_id = r.id
    ORDER BY ri.is_primary DESC, ri.sort_order, ri.id LIMIT 1
  ) img ON true
  WHERE r.status = 'available' AND b.status = 'active'
    AND rt.status = 'active' AND rc.status = 'active'
    AND rt.capacity >= p_guests
    AND (p_branch_id IS NULL OR r.branch_id = p_branch_id)
    AND (p_room_type_id IS NULL OR r.room_type_id = p_room_type_id)
    AND (p_min_price IS NULL OR r.price_per_night >= p_min_price)
    AND (p_max_price IS NULL OR r.price_per_night <= p_max_price)
    AND (SELECT count(*) FROM public.bookings bk
         WHERE bk.room_id = r.id
           AND bk.booking_status IN ('pending', 'confirmed', 'checked_in')
           AND bk.check_in_date < p_check_out_date
           AND bk.check_out_date > p_check_in_date) < r.inventory_count
  ORDER BY r.price_per_night, b.id, rt.id, rc.sort_order, r.id;
END;
$function$;

