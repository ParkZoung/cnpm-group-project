  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name character varying NOT NULL UNIQUE,
  description text,
  sort_order integer NOT NULL DEFAULT 0,
  status character varying NOT NULL DEFAULT 'active'
