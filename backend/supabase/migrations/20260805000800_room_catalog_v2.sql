CREATE OR REPLACE FUNCTION public.create_booking(
  p_room_id bigint, p_check_in_date date, p_check_out_date date,
  p_number_of_guests integer, p_guest_name text, p_guest_email text,
  p_guest_phone text, p_special_request text DEFAULT NULL
)
RETURNS TABLE (
  booking_id uuid, booking_code character varying,
  booking_status character varying, payment_status character varying,
  total_amount bigint, created_at timestamp with time zone
)
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
  v_user uuid := auth.uid();
  v_status character varying;
  v_price bigint;
  v_capacity integer;
  v_inventory integer;
  v_held integer;
  v_nights integer;
  v_subtotal bigint;
  v_tax bigint;
  v_total bigint;
  v_id uuid := pg_catalog.gen_random_uuid();
  v_now timestamp with time zone := pg_catalog.statement_timestamp();
  v_code character varying;
BEGIN
  IF v_user IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Authentication is required to create a booking.';
  END IF;
  SELECT p.status INTO v_status FROM public.profiles p WHERE p.id = v_user;
  IF v_status IS DISTINCT FROM 'active' THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'The authenticated profile is not allowed to create bookings.';
  END IF;
  IF p_check_in_date IS NULL OR p_check_out_date <= p_check_in_date
     OR p_check_in_date < CURRENT_DATE OR p_number_of_guests < 1 THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'The booking input is invalid.';
  END IF;

  SELECT r.price_per_night, rt.capacity, r.inventory_count
  INTO v_price, v_capacity, v_inventory
  FROM public.rooms r
  JOIN public.branches b ON b.id = r.branch_id AND b.status = 'active'
  JOIN public.room_types rt ON rt.id = r.room_type_id AND rt.status = 'active'
  JOIN public.room_classes rc ON rc.id = r.room_class_id AND rc.status = 'active'
  WHERE r.id = p_room_id AND r.status = 'available'
  FOR UPDATE OF r;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'The selected room is not available for booking.';
  END IF;
  IF p_number_of_guests > v_capacity THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'The guest count exceeds the selected room capacity.';
  END IF;

  SELECT count(*) INTO v_held FROM public.bookings bk
  WHERE bk.room_id = p_room_id
    AND bk.booking_status IN ('pending', 'confirmed', 'checked_in')
    AND bk.check_in_date < p_check_out_date
    AND bk.check_out_date > p_check_in_date;
  IF v_held >= v_inventory THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'The selected room class is sold out for those dates.';
  END IF;

  v_nights := p_check_out_date - p_check_in_date;
  v_subtotal := v_price * v_nights;
  v_tax := pg_catalog.round(v_subtotal::numeric * 0.10)::bigint;
  v_total := v_subtotal + v_tax;
  v_code := 'GS' || pg_catalog.to_char(v_now, 'YYYYMMDD') || '-' ||
    pg_catalog.upper(pg_catalog.substr(pg_catalog.replace(v_id::text, '-', ''), 1, 12));

  INSERT INTO public.bookings (
    id, booking_code, user_id, room_id, guest_name, guest_email, guest_phone,
    check_in_date, check_out_date, number_of_nights, number_of_guests,
    special_request, price_per_night, subtotal, tax_rate, tax_amount,
    discount_amount, total_amount, booking_status, payment_method,
    payment_status, created_at, updated_at, cancelled_at, promotion_id
  ) VALUES (
    v_id, v_code, v_user, p_room_id, pg_catalog.btrim(p_guest_name),
    pg_catalog.btrim(p_guest_email), pg_catalog.btrim(p_guest_phone),
    p_check_in_date, p_check_out_date, v_nights, p_number_of_guests,
    nullif(pg_catalog.btrim(p_special_request), ''), v_price, v_subtotal,
    10, v_tax, 0, v_total, 'pending', 'pay_at_hotel', 'unpaid',
    v_now, v_now, NULL, NULL
  );
  RETURN QUERY SELECT v_id, v_code, 'pending'::character varying,
    'unpaid'::character varying, v_total, v_now;
END;
$function$;
